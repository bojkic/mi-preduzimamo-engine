# frozen_string_literal: true

module Decidim
  module Bih
    module Admin
      # Round 25 — admin CRUD for the table-backed rewards catalog. Lets an
      # operator add/edit/retire a reward (cost/stock/expiry/active) without a
      # redeploy. Previously the catalog was initializer-only.
      #
      # Permission model: mirrors GoodwillController/ReportsController — gated on
      # current_user.admin? via ApplicationController#ensure_global_admin!. All
      # writes are org-scoped (current_organization), so one org's admin can
      # never touch another's catalog.
      #
      # i18n input: the form collects per-locale title/description via
      # title_<locale> params. Operators fill the Latin Serbian (sr) field; the
      # sr-Cyrl slot is auto-generated by the deterministic transliterator, the
      # same convention used for UI strings.
      class RewardsController < Decidim::Bih::Admin::ApplicationController
        include Decidim::Bih::Admin::ScopedFinder

        # Locales an operator fills directly. sr-Cyrl is derived from sr.
        INPUT_LOCALES = %w(sr bs hr).freeze
        WORKFLOW_TABS = %w(catalog stock diagnostics).freeze
        DEFAULT_WORKFLOW_TAB = "catalog"

        before_action -> { require_bih_permission!(:rewards_catalog_manage) }

        # GET /admin/bih/rewards
        def index
          @catalog_mode = Decidim::Bih::Goodwill::RewardsCatalog.mode(current_organization)
          @active_rewards_tab = active_workflow_tab
          @rewards = scoped_rewards.ordered
          @reward_stock_usage = reward_stock_usage if @active_rewards_tab == "stock"
        end

        # GET /admin/bih/rewards/new
        def new
          @reward = scoped_rewards.new(active: true)
        end

        # POST /admin/bih/rewards
        def create
          @reward = scoped_rewards.new(reward_attributes)
          if approval_rationale.blank?
            flash.now[:alert] = t(".approval_rationale_required")
            render :new, status: :unprocessable_entity
            return
          end

          if persist_with_audit { audit_operator_action!(
              "reward_created",
              permission: "rewards_catalog_manage",
              resource: @reward,
              metadata: {
                reward_key: @reward.key,
                active: @reward.active?,
                approval_rationale:
              }
            ) }
            flash[:notice] = t(".created")
            redirect_to admin_bih_rewards_path
          else
            flash.now[:alert] = t(".create_failed")
            render :new, status: :unprocessable_entity
          end
        end

        # GET /admin/bih/rewards/:id/edit
        # The finder redirects on a miss; the guard then halts so we never fall
        # through and render the edit template on top of that redirect.
        # rubocop:disable Style/RedundantReturn -- the `return` is load-bearing:
        # it halts the action on a not-found so the finder's redirect is the only
        # response; dropping it reintroduces the fall-through render bug.
        def edit
          return unless (@reward = find_reward!)
        end
        # rubocop:enable Style/RedundantReturn

        # PATCH/PUT /admin/bih/rewards/:id
        def update
          @reward = find_reward!
          return unless @reward

          @reward.assign_attributes(reward_attributes)
          changed_fields = @reward.changed
          if changed_fields.any? && approval_rationale.blank?
            flash.now[:alert] = t(".approval_rationale_required")
            render :edit, status: :unprocessable_entity
            return
          end

          if persist_with_audit { audit_operator_action!(
              "reward_updated",
              permission: "rewards_catalog_manage",
              resource: @reward,
              metadata: {
                reward_key: @reward.key,
                active: @reward.active?,
                changed_fields:,
                approval_rationale: approval_rationale.presence
              }
            ) }
            flash[:notice] = t(".updated")
            redirect_to admin_bih_rewards_path
          else
            flash.now[:alert] = t(".update_failed")
            render :edit, status: :unprocessable_entity
          end
        end

        # POST /admin/bih/rewards/:id/activate
        def activate
          toggle_active(true)
        end

        # POST /admin/bih/rewards/:id/deactivate
        def deactivate
          toggle_active(false)
        end

        def catalog
          mode = params[:mode].to_s
          unless Decidim::Bih::Goodwill::RewardsCatalog::MODES.include?(mode) && approval_rationale.present?
            flash[:alert] = t("decidim.bih.admin.rewards.catalog.invalid")
            return redirect_to admin_bih_rewards_path
          end
          current_organization.with_lock do
            Decidim::Bih::Setting.put(current_organization, Decidim::Bih::Goodwill::RewardsCatalog::NAMESPACE, "mode", mode)
            audit_operator_action!("reward_catalog_mode_changed", permission: "rewards_catalog_manage",
                                   metadata: { mode:, approval_rationale: })
          end
          flash[:notice] = t("decidim.bih.admin.rewards.catalog.updated")
          redirect_to admin_bih_rewards_path
        end

        private

        def persist_with_audit
          current_organization.with_lock do
            next false unless @reward.save

            yield
            true
          end
        end

        def scoped_rewards
          Decidim::Bih::Goodwill::Reward.where(organization: current_organization)
        end

        def active_workflow_tab
          requested = params[:tab].to_s
          return requested if WORKFLOW_TABS.include?(requested)

          DEFAULT_WORKFLOW_TAB
        end

        def reward_stock_usage
          reward_keys = @rewards.map(&:key)
          return {} if reward_keys.empty?

          Decidim::Bih::Goodwill::RewardFulfillment
            .where(organization: current_organization)
            .where(reward_key: reward_keys)
            .where.not(status: %w(canceled reversed))
            .group(:reward_key)
            .count
        end

        def find_reward!
          # Absolute key (not ".not_found"): this helper is called from several
          # actions, and a relative lookup would miss for actions without their
          # own not_found key (e.g. edit).
          find_scoped!(
            scoped_rewards,
            id: params[:id],
            redirect_to: admin_bih_rewards_path,
            flash_key: "decidim.bih.admin.rewards.not_found"
          )
        end

        def toggle_active(value)
          reward = find_reward!
          return unless reward

          if reward.active? == value
            flash[:notice] = value ? t(".activated") : t(".deactivated")
            redirect_to admin_bih_rewards_path
            return
          end

          if approval_rationale.blank?
            flash[:alert] = t(
              "decidim.bih.admin.rewards.#{value ? "activate" : "deactivate"}.approval_rationale_required"
            )
            redirect_to admin_bih_rewards_path
            return
          end

          begin
            current_organization.with_lock do
              reward.lock!
              reward.update!(active: value)
              audit_operator_action!(
                value ? "reward_activated" : "reward_deactivated",
                permission: "rewards_catalog_manage",
                resource: reward,
                metadata: { reward_key: reward.key, approval_rationale: }
              )
            end
          rescue ActiveRecord::RecordInvalid
            @active_rewards_tab = "catalog"
            @rewards = scoped_rewards.ordered
            @failed_reward_id = reward.id
            @approval_rationale_input = approval_rationale
            flash.now[:alert] = reward.errors.full_messages.to_sentence.presence ||
                                t("decidim.bih.admin.rewards.update.update_failed")
            return render :index, status: :unprocessable_entity
          end
          flash[:notice] = value ? t(".activated") : t(".deactivated")
          redirect_to admin_bih_rewards_path
        end

        # Maps the flat form params (title_sr, description_hr, …) into the model
        # attributes, building the locale-keyed jsonb hashes and deriving the
        # sr-Cyrl slot from the sr value via the transliterator.
        def reward_attributes
          {
            key: params.dig(:reward, :key).to_s.strip,
            cost: params.dig(:reward, :cost).presence,
            stock: params.dig(:reward, :stock).presence,
            expires_at: params.dig(:reward, :expires_at).presence,
            active: params.dig(:reward, :active).to_s.in?(%w(1 true on)),
            title: localized_hash(:title),
            description: localized_hash(:description)
          }
        end

        # Builds a { locale => value } hash from title_<locale> params and adds
        # the generated sr-Cyrl translation when sr is present.
        def localized_hash(field)
          hash = {}
          INPUT_LOCALES.each do |locale|
            value = params.dig(:reward, :"#{field}_#{locale}").to_s.strip
            hash[locale] = value if value.present?
          end
          hash["sr-Cyrl"] = Decidim::Bih::Transliterator.call(hash["sr"]) if hash["sr"].present?
          hash
        end

        def approval_rationale
          params[:approval_rationale].to_s.strip
        end
      end
    end
  end
end
